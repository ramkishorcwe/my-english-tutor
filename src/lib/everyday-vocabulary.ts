type Word = { word: string; meaning: string; example: string };
type Category = { id: string; title: string; description: string; words: Word[] };
function category(
  id: string,
  title: string,
  description: string,
  rows: [string, string, string][],
): Category {
  return {
    id,
    title,
    description,
    words: rows.map(([word, meaning, example]) => ({ word, meaning, example })),
  };
}

